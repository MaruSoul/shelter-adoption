<?php

use App\Rules\Iban;

it('приймає правильний український IBAN з пробілами чи без', function (string $iban) {
    expect(Iban::isValid($iban))->toBeTrue();
})->with(['UA213223130000026007233566001', 'UA21 3223 1300 0002 6007 2335 6600 1', 'ua213223130000026007233566001']);

it('відхиляє IBAN з помилкою в цифрі, іншої країни чи неповний', function (string $iban) {
    expect(Iban::isValid($iban))->toBeFalse();
})->with(['UA213223130000026007233566002', 'DE89370400440532013000', 'UA2132231300000260072335660', '']);

it('показує IBAN групами по 4 символи', function () {
    expect(Iban::format('UA213223130000026007233566001'))->toBe('UA21 3223 1300 0002 6007 2335 6600 1');
});
